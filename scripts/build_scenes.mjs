import { readFile, readdir, mkdir, writeFile, rename, unlink } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { pathToFileURL } from "node:url";
import { validateScene } from "../frontend/scenes/validate.mjs";
import { compileMermaidScene } from "../frontend/scenes/mermaid.mjs";
import { renderScene, renderCatalog, renderSceneCatalog, GENERATED_MARKER } from "../frontend/scenes/render.mjs";

const root = resolve(import.meta.dirname, "..");
const ownedMarkers = [GENERATED_MARKER, "<!-- Generated by build:scenes; edit scenes/*.json instead. -->"];
const isGenerated = (content) => ownedMarkers.some((marker) =>
  content.replace(/\r\n/g, "\n").startsWith(`<!DOCTYPE html>\n${marker}`));
export async function loadScenes(sourceDir = resolve(root, "scenes")) {
  const names = (await readdir(sourceDir, { withFileTypes: true })).filter((file) => file.isFile()).map((file) => file.name);
  const files = names.filter((name) => name.endsWith(".json")).sort();
  for (const name of names.filter((name) => name.endsWith(".mmd"))) {
    if (!names.includes(`${name.slice(0, -4)}.json`)) throw new Error(`${name}: 缺少同名 .json 场景元数据`);
  }
  const scenes = [];
  // Validate and render the entire input before touching existing output files.
  for (const file of files) scenes.push(await loadSceneFile(resolve(sourceDir, file)));
  return scenes;
}

export async function loadSceneFile(filePath) {
  const sourceDir = dirname(filePath), file = filePath.split(/[\\/]/).at(-1);
  const slug = file.slice(0, -5);
  if (!file.endsWith(".json") || !/^[a-z0-9][a-z0-9_-]*$/.test(slug) || slug === "index") {
    throw new Error(`${file}: 文件名应为小写字母、数字、连字符或下划线，不能使用 index`);
  }
  const schema = JSON.parse(await readFile(resolve(root, "schema/sequence-scene.schema.json"), "utf8"));
  const metadataSchema = JSON.parse(await readFile(resolve(root, "schema/mermaid-scene.schema.json"), "utf8"));
  try {
    const data = JSON.parse(await readFile(filePath, "utf8"));
    const mermaidFile = `${slug}.mmd`;
    const source = await readFile(resolve(sourceDir, mermaidFile), "utf8").catch((error) => {
      if (error.code === "ENOENT") return null;
      throw error;
    });
    const scene = source === null ? validateScene(data, schema)
      : compileMermaidScene(data, source, schema, metadataSchema, mermaidFile);
    return { slug, scene };
  } catch (error) {
    throw new Error(`${file}: ${error.message}`, { cause: error });
  }
}

export async function buildScenes({
  sourceDir = resolve(root, "scenes"), outputDir = resolve(root, "public/scenes"), check = false,
} = {}) {
  const scenes = await loadScenes(sourceDir);
  const output = new Map(scenes.map(({ slug, scene }) => [`${slug}.html`, renderScene(scene, slug)]));
  output.set("index.html", renderCatalog(scenes));
  output.set("catalog.json", renderSceneCatalog(scenes));
  const currentFiles = await readdir(outputDir).catch((error) => {
    if (error.code === "ENOENT") return [];
    throw error;
  });
  // Check all collisions before writing any page, including the generated catalog.
  for (const name of output.keys()) {
    const content = await readFile(resolve(outputDir, name), "utf8").catch((error) => {
      if (error.code === "ENOENT") return null;
      throw error;
    });
    let owned = content === null || isGenerated(content);
    if (name === "catalog.json" && content !== null) {
      try { owned = JSON.parse(content).generatedBy === "build:scenes"; } catch { owned = false; }
    }
    if (!owned) {
      throw new Error(`${name}: 已存在非生成的 ${name.endsWith(".html") ? "HTML 文件" : "目录文件"}，请先重命名或迁移，构建不会覆盖手写内容`);
    }
  }
  const stale = [];
  for (const name of currentFiles.filter((name) => name.endsWith(".html") && !output.has(name))) {
    const content = await readFile(resolve(outputDir, name), "utf8");
    if (isGenerated(content)) stale.push(name);
  }
  if (check) {
    const changed = [...stale];
    for (const [name, expected] of output) {
      const actual = await readFile(resolve(outputDir, name), "utf8").catch((error) => {
        if (error.code === "ENOENT") return "";
        throw error;
      });
      if (actual.replace(/\r\n/g, "\n") !== expected) changed.push(name);
    }
    if (changed.length) throw new Error(`场景产物未同步：${changed.join(", ")}；运行 npm run build:scenes`);
  } else {
    await mkdir(outputDir, { recursive: true });
    for (const [name, content] of output) {
      const target = resolve(outputDir, name);
      if (dirname(target) !== resolve(outputDir)) throw new Error("场景产物路径越界");
      const temporary = `${target}.${process.pid}.tmp`;
      try {
        await writeFile(temporary, content, "utf8");
        await rename(temporary, target);
      } finally {
        await unlink(temporary).catch((error) => { if (error.code !== "ENOENT") throw error; });
      }
    }
    for (const name of stale) await unlink(resolve(outputDir, name));
  }
  return scenes.length;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const count = await buildScenes({ check: process.argv.includes("--check") });
    console.log(`Scenes: ${count} independent pages ${process.argv.includes("--check") ? "verified" : "built"}`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
