import assert from "node:assert/strict";
import { mkdtemp, mkdir, writeFile, readFile, rm, symlink } from "node:fs/promises";
import { resolve, dirname, basename } from "node:path";
import { tmpdir } from "node:os";
import { checkContent } from "../scripts/check_content.mjs";
import { buildScenes } from "../scripts/build_scenes.mjs";
import { readEvidence } from "../scripts/content/evidence.mjs";

const root = await mkdtemp(resolve(tmpdir(), "callgraph-content-test-"));
const save = (name, value) => writeFile(resolve(root, name), typeof value === "string" ? value : JSON.stringify(value));
try {
  for (const dir of ["graphs", "scenes", "public/scenes", "checkout"]) await mkdir(resolve(root, dir), { recursive: true });
  await save("callgraph.projects.json", { schemaVersion: "0.1", projects: [{ id: "test", root: "checkout" }] });
  await save("checkout/a.py", "def run():\n    return 1\n");
  const metadata = { schemaVersion: "1.0", title: "测试", summary: "示例", project: { id: "test", label: "Test", revision: "fixture" }, scope: { startEnd: "开始到结束", boundary: "本地" }, evidence: [{ id: "e1", claim: "返回 1", status: "source", locations: [{ file: "a.py", line: 1, endLine: 2, symbol: "run", anchor: "def run():" }] }] };
  await save("scenes/test.json", metadata);
  await save("scenes/test.mmd", "sequenceDiagram\n%% @evidence e1\nA->>A: 返回 1\n");
  const build = () => buildScenes({ sourceDir: resolve(root, "scenes"), outputDir: resolve(root, "public/scenes") });
  await build();
  const options = { root, project: "test", graphValidator: () => ({ valid: true, warnings: [], errors: [] }) };
  assert.equal((await checkContent(options)).valid, true);
  assert.equal((await checkContent({ ...options, snapshot: true })).valid, true);
  const baseline = await readFile(resolve(root, "evidence/baselines/test.json"), "utf8");
  assert.equal((await checkContent(options)).fingerprintMatches, 1);
  await save("checkout/a.py", "def run():\r\n    return 1\r\n");
  assert.equal((await checkContent(options)).fingerprintMatches, 1, "line endings do not cause drift");
  await save("checkout/a.py", "def run():\n    return 2\n");
  let result = await checkContent(options);
  assert.equal(result.valid, false);
  assert.ok(result.diagnostics.some((d) => d.code === "evidence-stale"));
  assert.equal(await readFile(resolve(root, "evidence/baselines/test.json"), "utf8"), baseline, "checking never blesses changed source");
  await save("checkout/a.py", "def renamed():\n    return 2\n");
  result = await checkContent({ ...options, snapshot: true });
  assert.equal(result.valid, false, "invalid anchors prevent baseline writes");
  assert.equal(await readFile(resolve(root, "evidence/baselines/test.json"), "utf8"), baseline);
  await save("checkout/a.py", "def run():\n    return 1\n");
  metadata.evidence[0].claim = "改变结论也需要复核";
  await save("scenes/test.json", metadata);
  await build();
  assert.ok((await checkContent(options)).diagnostics.some((d) => d.code === "evidence-stale"));
  await assert.rejects(readEvidence(resolve(root, "checkout"), { file: "../callgraph.projects.json" }), /相对路径/);
  await assert.rejects(readEvidence(resolve(root, "checkout"), { file: "a.py", line: 999 }), /范围无效/);
  await save("checkout/binary", Buffer.from([0]).toString());
  await assert.rejects(readEvidence(resolve(root, "checkout"), { file: "binary" }), /二进制/);
  await symlink(root, resolve(root, "checkout/outside"), process.platform === "win32" ? "junction" : "dir");
  await assert.rejects(readEvidence(resolve(root, "checkout"), { file: "outside/callgraph.projects.json" }), /越过/);
  await save("scenes/bad.json", "{");
  await save("scenes/orphan.mmd", "sequenceDiagram");
  await save("graphs/bad.json", "{");
  result = await checkContent({ root, graphValidator: options.graphValidator });
  assert.equal(result.valid, false);
  for (const code of ["graph-invalid", "scene-invalid", "metadata-missing"]) assert.ok(result.diagnostics.some((d) => d.code === code), code);
  await assert.rejects(checkContent({ root, project: "unknown" }), /没有 unknown/);
} finally {
  assert.equal(dirname(root), resolve(tmpdir()));
  assert.ok(basename(root).startsWith("callgraph-content-test-"));
  await rm(root, { recursive: true });
}
console.log("Content checks: drift, anchors, failure preservation, aggregated errors, project filters and source boundaries passed");
