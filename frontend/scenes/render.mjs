// Deterministic layout, shared by every scene. Data supplies meaning, never geometry.
export const GENERATED_MARKER = "<!-- Generated by build:scenes; edit sources in scenes/ instead. -->";
export const escapeHtml = (value) => String(value).replace(/[&<>"']/g, (char) => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
})[char]);
const e = escapeHtml;
const LINE = 22;

// Conservative glyph advances keep layout independent of browser font loading.
// Unbroken identifiers are wrapped too; no text is truncated to fit a box.
export function wrapText(value, width, fontSize = 14) {
  const lines = [];
  const segmenter = new Intl.Segmenter("zh", { granularity: "grapheme" });
  const words = new Intl.Segmenter("zh", { granularity: "word" });
  const advanceOf = (segment) => fontSize * (/[^\x00-\xff]/.test(segment)
    ? 1.1 : /[MW@%]/.test(segment) ? 1 : .72);
  for (const paragraph of value.split(/\r?\n/)) {
    let line = "", advance = 0;
    for (const word of words.segment(paragraph)) {
      const glyphs = [...segmenter.segment(word.segment)].map((item) => item.segment);
      const wordWidth = glyphs.reduce((sum, glyph) => sum + advanceOf(glyph), 0);
      if (line && wordWidth <= width && advance + wordWidth > width) {
        lines.push(line); line = ""; advance = 0;
      }
      for (const segment of glyphs) {
        const size = advanceOf(segment);
        if (line && advance + size > width) {
          lines.push(line); line = ""; advance = 0;
        }
        line += segment; advance += size;
      }
    }
    lines.push(line || " ");
  }
  return lines;
}

function text(lines, x, y, cls, anchor = "start") {
  return `<text x="${x}" y="${y}" class="${cls}" text-anchor="${anchor}">${lines.map(
    (line, i) => `<tspan x="${x}" dy="${i ? LINE : 0}">${e(line)}</tspan>`,
  ).join("")}</text>`;
}

function depthOf(body) {
  return Math.max(0, ...body.map((block) => block.body ? 1 + depthOf(block.body)
    : block.branches ? 1 + Math.max(...block.branches.map((b) => depthOf(b.body))) : 0));
}

export function renderSequence(scene, slug) {
  const depth = depthOf(scene.body);
  const gap = 280;
  // Include the full outer actor card, even for a flow without nested frames.
  const margin = Math.max(148, 90 + depth * 20);
  const width = Math.max(1000, margin * 2 + (scene.participants.length - 1) * gap);
  const firstX = (width - (scene.participants.length - 1) * gap) / 2;
  const xs = new Map(scene.participants.map((actor, i) => [actor.id, firstX + i * gap]));
  const actorLabels = scene.participants.map((actor) => ({
    title: wrapText(actor.label, 220, 16), role: actor.role ? wrapText(actor.role, 220, 11) : [],
  }));
  const actorHeight = Math.max(...actorLabels.map((label) => (label.title.length + label.role.length) * LINE + 24));
  const bodyY = actorHeight + 64;
  const evidenceIndex = new Map(scene.evidence.map((item, i) => [item.id, i + 1]));
  const evidenceSuffix = (block) => block.evidence?.length
    ? `〔依据 ${block.evidence.map((id) => evidenceIndex.get(id)).join("、")}〕` : "";

  const linked = (block, markup) => block.evidence?.length
    ? `<a href="#evidence-${e(block.evidence[0])}" aria-label="核对源码依据">${markup}</a>` : markup;

  function layout(body, top, level = 0) {
    let y = top;
    const content = [];
    for (const block of body) {
      const inset = 24 + level * 20;
      if (block.type === "message") {
        const from = xs.get(block.from), to = xs.get(block.to);
        const self = from === to;
        const direction = from + gap <= width - 40 ? 1 : -1;
        const labelX = self ? from + direction * gap / 2 : (from + to) / 2;
        const labelWidth = self ? gap - 60 : Math.min(Math.abs(from - to) - 32, 660);
        const lines = wrapText(block.label + evidenceSuffix(block), labelWidth);
        const arrowY = y + lines.length * LINE + 12;
        const marker = block.kind === "async" ? "open" : block.kind === "call" ? "blue" : "filled";
        const arrow = self
          ? `<path class="message ${block.kind}" d="M${from} ${arrowY} h${direction * 42} v24 h${-direction * 42}" marker-end="url(#${slug}-${marker})"/>`
          : `<line class="message ${block.kind}" x1="${from}" y1="${arrowY}" x2="${to}" y2="${arrowY}" marker-end="url(#${slug}-${marker})"/>`;
        content.push(`<g class="exchange" data-kind="${block.kind}" data-from="${e(block.from)}" data-to="${e(block.to)}">${linked(block, text(lines, labelX, y + 16, "message-label", "middle"))}${arrow}</g>`);
        y = arrowY + (self ? 24 : 0) + 32;
      } else if (block.type === "note") {
        const positions = (block.over || scene.participants.map((a) => a.id)).map((id) => xs.get(id));
        const left = Math.max(inset + 12, Math.min(...positions) - 120);
        const right = Math.min(width - inset - 12, Math.max(...positions) + 120);
        const lines = wrapText(block.text + evidenceSuffix(block), right - left - 32, 12);
        const height = lines.length * LINE + 28;
        content.push(`<g class="sequence-note"><rect class="note-box" x="${left}" y="${y}" width="${right - left}" height="${height}" rx="3"/>${linked(block, text(lines, left + 16, y + 25, "note"))}</g>`);
        y += height + 24;
      } else {
        const start = y;
        const branches = block.branches || [{ condition: block.condition, body: block.body }];
        y += 40;
        const fragments = [];
        branches.forEach((branch, i) => {
          if (i) {
            fragments.push(`<line class="divider" x1="${inset}" y1="${y}" x2="${width - inset}" y2="${y}"/>`);
            y += 28;
          }
          const guard = wrapText(`[${branch.condition}]`, width - inset * 2 - 32, 12);
          fragments.push(text(guard, inset + 16, y, "guard"));
          y += guard.length * LINE + 16;
          const nested = layout(branch.body, y, level + 1);
          fragments.push(nested.markup);
          y = nested.bottom + 12;
        });
        content.push(`<g class="fragment" data-operator="${block.type}"><rect class="frame" x="${inset}" y="${start}" width="${width - inset * 2}" height="${y - start}" rx="4"/><rect class="frame-tab" x="${inset}" y="${start}" width="54" height="21" rx="2"/>${text([block.type.toUpperCase()], inset + 27, start + 14, "operator", "middle")}${fragments.join("\n")}</g>`);
        y += 24;
      }
    }
    return { markup: content.join("\n"), bottom: y };
  }

  const body = layout(scene.body, bodyY);
  const bottomActorsY = body.bottom + 8;
  const height = bottomActorsY + actorHeight + 24;
  const actors = scene.participants.map((actor, i) => {
    const x = xs.get(actor.id), label = actorLabels[i];
    const tone = ["blue", "teal", "orange", "plum"][i % 4];
    const card = (y, position) => `<g class="actor" data-tone="${tone}" data-position="${position}"><rect x="${x - 124}" y="${y}" width="248" height="${actorHeight}" rx="4"/>
${text(label.title, x, y + 26, "actor-label", "middle")}
${label.role.length ? text(label.role, x, y + 26 + label.title.length * LINE, "actor-role", "middle") : ""}</g>`;
    return `<line class="lifeline" x1="${x}" y1="${actorHeight + 24}" x2="${x}" y2="${bottomActorsY}"/>
${card(24, "top")}${card(bottomActorsY, "bottom")}`;
  }).join("\n");
  return `<svg xmlns="http://www.w3.org/2000/svg" class="sequence" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}" role="img" aria-labelledby="${slug}-title ${slug}-desc">
<title id="${slug}-title">${e(scene.title)}</title><desc id="${slug}-desc">${e(scene.summary)}</desc>
<defs>
<marker id="${slug}-blue" markerWidth="8" markerHeight="8" refX="7" refY="4" orient="auto"><path class="marker-call" d="M0 0 L8 4 L0 8 Z"/></marker>
<marker id="${slug}-filled" markerWidth="8" markerHeight="8" refX="7" refY="4" orient="auto"><path class="marker-return" d="M0 0 L8 4 L0 8 Z"/></marker>
<marker id="${slug}-open" markerWidth="9" markerHeight="8" refX="8" refY="4" orient="auto"><path class="marker-async" d="M0 0 L8 4 L0 8" fill="none" stroke-width="1.4"/></marker>
</defs>${actors}${body.markup}</svg>`;
}

function document(title, description, body, theme = "editorial") {
  return `<!DOCTYPE html>\n${GENERATED_MARKER}
<html lang="zh-CN" data-theme="${e(theme)}"><head><meta charset="utf-8"/><meta name="viewport" content="width=device-width, initial-scale=1"/>
<meta name="description" content="${e(description)}"/><title>${e(title)} · 场景地图</title><link rel="stylesheet" href="/scenes/scenes.css"/></head>
<body><main class="page">${body}</main></body></html>\n`;
}

const callgraphLink = (scene, label) => scene.callgraph
  ? `<a class="callgraph-link" href="/?graph=${encodeURIComponent(scene.callgraph)}">${label}</a>` : "";
const projectLink = (scene) => scene.project.id
  ? `<a class="project-home-link" href="/?project=${encodeURIComponent(scene.project.id)}">← 项目目录 · ${e(scene.project.label)}</a>`
  : '<a class="project-home-link" href="/">← 项目主页</a>';

export function renderScene(scene, slug) {
  return document(scene.title, scene.summary, `
<nav class="page-nav" aria-label="页面导航">${projectLink(scene)}<a href="/scenes/index.html${scene.project.id ? `#project-${e(scene.project.id)}` : ""}">场景目录</a>${callgraphLink(scene, "查看调用图 →")}</nav>
<header><p class="kicker">${e(scene.project.label)} · EXECUTION SEQUENCE</p><h1>${e(scene.title)}</h1><p class="lead">${e(scene.summary)}</p>
<dl class="scope"><div><dt>开始 → 结束</dt><dd>${e(scene.scope.startEnd)}</dd></div><div><dt>本页范围</dt><dd>${e(scene.scope.boundary)}</dd></div>${scene.scope.notes ? `<div><dt>阅读提示</dt><dd>${e(scene.scope.notes)}</dd></div>` : ""}</dl></header>
<section aria-labelledby="sequence-heading"><div class="figure-heading"><h2 id="sequence-heading">执行时序</h2><p>按语义展开 · 窄屏可横向滚动</p></div>
<div class="legend" aria-label="消息图例"><span data-kind="call">实线实心箭头：调用 / 请求</span><span data-kind="return">虚线实心箭头：返回 / 结果</span><span data-kind="async">虚线空心箭头：异步派发 / 事件</span></div>
<figure><div class="diagram-scroll" tabindex="0" role="region" aria-label="可横向滚动的完整时序图">${renderSequence(scene, slug)}</div>
<figcaption>从上向下阅读；间距不表示耗时，PAR 分区之间不表示执行或完成先后。角色配色辅助对齐泳道；区域颜色对应控制流类型，不表示风险或重要性。${e(scene.caption || "")}</figcaption></figure></section>
${scene.reading ? `<section class="reading" aria-label="读图要点">${scene.reading.map((item) => `<article><h3>${e(item.title)}</h3><p>${e(item.text)}</p></article>`).join("")}</section>` : ""}
<section class="evidence" id="evidence"><h2>核对执行依据</h2><p>源码基线：${e(scene.project.label)} <code>${e(scene.project.revision)}</code>。图中箭头按职责归纳，不保证逐一对应函数调用；下列位置用于核对结论。</p>
<ol>${scene.evidence.map((item) => `<li id="evidence-${e(item.id)}">${e(item.claim)} <small>${item.status === "inferred" ? "推断 · 需进一步核对" : item.status === "source" ? "源码依据 · 作者核对" : "依据分类未标注"}</small><br/>${item.locations.map((location) => `<code>${e(location.file)}${location.line ? `:${location.line}${location.endLine ? `–${location.endLine}` : ""}` : "（文件级依据）"}</code> · <code>${e(location.symbol)}</code>`).join("<br/>")}</li>`).join("\n")}</ol>
<p>${callgraphLink(scene, "打开调用图，核对函数、调用点和源码 →")}</p></section>
<footer class="page-footer">${projectLink(scene)}${callgraphLink(scene, "查看调用图 →")}</footer>`, scene.theme);
}

export function renderCatalog(scenes) {
  const projects = new Map();
  for (const entry of scenes) {
    const key = entry.scene.project.id || "unassigned";
    if (!projects.has(key)) projects.set(key, []);
    projects.get(key).push(entry);
  }
  return document("场景地图", "从场景理解执行，再通过调用图核对源码。", `
<nav class="page-nav"><span class="wordmark">CodeRova / SCENARIOS</span><a href="/">全部项目与地图 →</a></nav>
<header><p class="kicker">EXECUTION SEQUENCES</p><h1>场景地图</h1><p class="lead">先读懂谁在协作、消息如何传递，以及执行为什么继续或结束。每张图独立阅读，按需跳转调用图核对源码。</p></header>
<nav class="project-index" aria-label="按项目阅读">${[...projects].map(([id, entries]) => `<a href="#project-${e(id)}">${e(id === "unassigned" ? "未关联项目" : entries[0].scene.project.label)} <small>${entries.length}</small></a>`).join("")}</nav>
${[...projects].map(([id, entries]) => `<section class="scene-list" id="project-${e(id)}"><div class="project-section-heading"><h2>${e(id === "unassigned" ? "未关联项目" : entries[0].scene.project.label)}</h2>${projectLink(entries[0].scene)}</div>${entries.map(({ slug, scene }, i) => `<article class="scene-entry"><span class="number">${String(i + 1).padStart(2, "0")}</span><div><h3><a href="${slug}.html">${e(scene.title)}</a></h3><p>${e(scene.summary)}</p></div><a href="${slug}.html">阅读场景 →</a></article>`).join("\n")}</section>`).join("\n")}`);
}

export function renderSceneCatalog(scenes) {
  return JSON.stringify({ schemaVersion: "1.0", generatedBy: "build:scenes", scenes: scenes.map(({ slug, scene }) => ({
    slug, projectId: scene.project.id || null, projectLabel: scene.project.label,
    title: scene.title, summary: scene.summary, callgraph: scene.callgraph || null,
  })) }, null, 2) + "\n";
}
